def write(res_root):
    base = os.path.join(res_root, 'assets', 'hermodoors', 'lang')
    os.makedirs(base, exist_ok=True)
    missing = sorted(set(EN) ^ set(RU))
    if missing:
        raise SystemExit(f'lang keys differ between en_us and ru_ru: {missing}')
    for name, table in (('en_us', EN), ('ru_ru', RU)):
        data = dict(table)
        data.update(ENGRAVINGS)
        with open(os.path.join(base, f'{name}.json'), 'w', encoding='utf-8') as f:
            json.dump(dict(sorted(data.items())), f, ensure_ascii=False, indent=2)
            f.write('\n')
